#!/bin/bash
#
#   linux-test.sh - Build and run the suite inside the Linux test container.
#
#   Invoked by bin/test-linux.sh; not useful on its own. Two mounts are in place:
#
#       /src    the host working tree, read only
#       /work   a container volume holding the Linux build
#
#   The tree is staged from /src into /work rather than built in place. build/obj is per platform
#   but build/bin is not, so a Linux build in the host tree would overwrite the macOS binaries and
#   leave make believing they were up to date -- the host suite would then run ELF binaries and
#   fail in a way that looks nothing like its cause. The volume also survives between runs, so the
#   second build is incremental.
#
#   Arguments are passed to tm. With none, the whole suite runs, which is what "make test" does.
#
set -u

if [ ! -d /src ] || [ ! -d /work ] ; then
    echo "      [Error] linux-test.sh runs inside the test container only" >&2
    exit 255
fi

#
#   The script runs twice: once as root to stage the tree, then again as an ordinary user to build
#   and test. The marker below is what tells the second pass which it is.
#
#   A container's entrypoint is root, and running the suite as root does not measure what anyone
#   ships. web.user defaults to "nobody", so a root-started server drops privileges and then runs
#   as a different user than the one that staged the tree; every PUT, DELETE and upload into the
#   root-owned document tree fails with 500. That is the server behaving correctly, and it is not
#   the configuration CI, a developer, or this harness is meant to measure. CI's ubuntu runner is
#   unprivileged, so matching it here keeps the two results comparable.
#
#   Root does exercise a path nothing else covers, and it found two real defects: web issue 61,
#   fixed, and web issue 63, open -- the upload directory is validated against the pre-drop
#   identity, so a root-started server can never accept an upload. Reproduce either with
#   "IOTO_LINUX_ROOT=1 make test-linux", which stages as before and then stays root. Once 63 is
#   fixed, a root run belongs here as a deliberate mode rather than as an accident of how
#   containers start.
#
if [ -z "${IOTO_LINUX_STAGED:-}" ] ; then
    #
    #   .testme must be excluded, not merely refreshed. TestMe caches each compiled .tst.c beside
    #   its source and reuses it when it is newer than the source, so a host run leaves Mach-O
    #   binaries that this container would decide were up to date and then fail to exec.
    #
    #   .local.mk is not in the repository and is not part of anyone else's build. It is included
    #   by the top-level Makefile when present and calls host-only tools, so staging it would mean
    #   this container builds something neither CI nor a customer does.
    #
    #   apps/*/state is generated by bin/prepare at build time and holds the certificates and
    #   blended configuration for a host run. Staging it carries a macOS run's state into Linux.
    #
    #   --delete-excluded, not just --delete: an excluded file is protected from deletion by
    #   default, so anything staged by an earlier version of this script would live in the volume
    #   forever. The two things the container owns and the host must never supply -- the Linux
    #   build and TestMe's compile cache -- are protected explicitly instead.
    #
    echo "       [Run] stage /src into /work"
    rsync -a --delete --delete-excluded \
        --filter 'protect /build/' \
        --filter 'protect .testme/' \
        --exclude '.git' \
        --exclude '.local.mk' \
        --exclude '.testme' \
        --exclude '.testme-pidfile' \
        --exclude '.DS_Store' \
        --exclude 'build' \
        --exclude 'node_modules' \
        --exclude 'doc' \
        --exclude 'apps/*/state' \
        /src/ /work/ || exit 255

    if [ -z "${IOTO_LINUX_ROOT:-}" ] ; then
        echo "       [Run] hand /work to ubuntu and drop root"
        chown -R ubuntu:ubuntu /work || exit 255
        exec setpriv --reuid=ubuntu --regid=ubuntu --init-groups \
            env HOME=/home/ubuntu IOTO_LINUX_STAGED=1 PATH="$PATH" \
            bash "$0" ${1+"$@"}
    fi
fi

cd /work || exit 255

#   The suite needs the debug configuration, as "make test" builds it
echo "       [Run] make OPTIMIZE=debug [linux]"
make OPTIMIZE=debug || exit 255

#
#   Report what was actually exercised. The image is arm64 and CI's ubuntu runner is x86_64, so
#   this line is the difference between the two results.
#
echo "      [Info] $(uname -s) $(uname -m), gcc $(gcc -dumpversion 2>/dev/null), $(openssl version 2>/dev/null)"

./bin/prep-test.sh || exit 255

if [ $# -eq 0 ] ; then
    set -- test
fi

# Rebuild cached tests when their statically linked library changes.
if [ -n "$(find test -type f -perm -u+x ! -newer build/bin/libioto.a -print -quit 2>/dev/null)" ] ; then
    echo "      [Info] library is newer than the test binaries - rebuilding"
    set -- --rebuild "$@"
fi
echo "       [Run] tm $*"
tm "$@"
